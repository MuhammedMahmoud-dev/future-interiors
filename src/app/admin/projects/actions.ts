/**
 * Every action here re-checks the admin session. A Server Action is a public
 * HTTP endpoint — being rendered by a guarded page is not itself protection.
 *
 * Writes use the service_role client, which is the only thing RLS lets through.
 */

export type LedgerKind = "expenses" | "payments";

export type LedgerRow = {
  /** Stable client-side key. New rows have no id yet. */
  key: string;
  id: string | null;
  date: string;
  text: string;
  amount: string;
  stageId?: string | null;
};

export type SavedRow = { key: string; id: string };

function publicRevalidate() {
  // Content and projects feed the public site and the client portal alike.
  revalidatePath("/[locale]", "layout");
}

function requireDb() {
  const supabase = getSupabase();
  if (!supabase) throw new Error("Supabase is not configured");
  return supabase;
}

/** Empty string -> null, so optional columns stay NULL instead of "". */
function text(formData: FormData, field: string): string | null {
  const value = String(formData.get(field) ?? "").trim();
  return value === "" ? null : value;
}

/**
 * Turns the form's client selection into a client_id.
 *
 * Either an existing client was picked, or a new one was typed in. On the new
 * path, a phone that already belongs to someone links to that existing client
 * rather than erroring on the unique index — a returning client opening a
 * second apartment is the case this table was added for, and it should not read
 * as a validation failure.
 */
async function resolveClientId(formData: FormData): Promise<string | null> {
  const existing = String(formData.get("client_id") ?? "").trim();
  if (existing) return existing;

  const name = String(formData.get("new_client_name") ?? "").trim();
  const phone = normalizePhone(String(formData.get("new_client_phone") ?? ""));

  // Neither picked nor typed: leave the project unlinked rather than inventing
  // a blank client. The admin can attach one later.
  if (!name && !phone) return null;

  if (!name) throw new Error("اسم العميل مطلوب");
  if (!/^1\d{9}$/.test(phone)) throw new Error("رقم موبايل العميل مش صحيح (مثال: 01115134141)");

  const supabase = requireDb();

  const { data: match } = await supabase
    .from("clients")
    .select("id")
    .eq("phone", phone)
    .maybeSingle();
  if (match) return match.id as string;

  const { data, error } = await supabase
    .from("clients")
    .insert({ name, phone })
    .select("id")
    .single();
  if (error) throw new Error(error.message);

  return data.id as string;
}

function projectPayload(formData: FormData) {
  const rate = parseAmount(String(formData.get("supervision_rate") ?? ""));
  const area = parseAmount(String(formData.get("area_m2") ?? ""));
  const status = String(formData.get("status") ?? "in_progress");

  if (rate === null || rate < 0 || rate > 1) {
    throw new Error("نسبة الإشراف لازم تكون بين 0 و 1 (مثال: 0.15)");
  }
  if (!["in_progress", "completed", "on_hold"].includes(status)) {
    throw new Error("حالة المشروع مش صحيحة");
  }

  const title = String(formData.get("title_ar") ?? "").trim();
  if (!title) throw new Error("عنوان المشروع مطلوب");

  // No slug here. It is derived from the project code after the row exists —
  // see resolveSlug below — because the code is generated by the database.
  return {
    title_ar: title,
    title_en: text(formData, "title_en"),
    // description_ar / description_en are no longer collected: nothing renders
    // them. Omitted from the payload rather than written as null, so whatever a
    // row already holds survives a save.
    unit_no: text(formData, "unit_no"),
    building_no: text(formData, "building_no"),
    supervision_rate: rate,
    compound: text(formData, "compound"),
    district: text(formData, "district"),
    area_m2: area,
    start_date: text(formData, "start_date"),
    end_date: text(formData, "end_date"),
    status,
    is_public: formData.get("is_public") === "on",
    // Unchecked boxes are simply absent from the payload, so this reads false
    // only when the engineer actually cleared it.
    portal_access_enabled: formData.get("portal_access_enabled") === "on",
    // Publishing requires an explicit approval timestamp as well as the flag.
    publish_approved_at:
      formData.get("publish_approved_at") === "on" ? new Date().toISOString() : null,
  };
}

/**
 * The code-derived slug, numbered past anything already holding it.
 *
 * One query for every slug sharing the prefix, rather than one per attempt.
 * `excludeId` keeps a project from colliding with itself.
 */
async function resolveSlug(
  supabase: ReturnType<typeof requireDb>,
  code: string,
  excludeId: string,
): Promise<string> {
  const base = slugFromCode(code);
  const { data } = await supabase.from("projects").select("id,slug").like("slug", `${base}%`);
  const taken = (data ?? []).filter((row) => row.id !== excludeId).map((row) => row.slug);
  return firstFreeSlug(base, taken);
}

/*
 * setProjectStatus was here: a Server Action that set projects.status on its
 * own. Nothing ever called it — not in any commit since it was written — and
 * status is edited through the select in ProjectForm, which saves with the
 * rest of the project. It was a second write path to a field that already had
 * one, and an HTTP endpoint nobody needed.
 */

/** Validation failures come back as a message for the form; success redirects. */
export type ProjectFormState = { error: string | null; savedAt?: number };

export async function createProject(
  _previous: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  await requireAdmin();
  const supabase = requireDb();

  let id: string;
  try {
    const client_id = await resolveClientId(formData);

    /*
     * Two statements, because the slug comes from the code and the code comes
     * from the database default — it does not exist until the row does. The
     * placeholder holds the NOT NULL UNIQUE column for the moment in between,
     * and is chosen so it cannot collide with a real slug.
     */
    const { data, error } = await supabase
      .from("projects")
      .insert({
        ...projectPayload(formData),
        client_id,
        slug: `pending-${randomUUID()}`,
      })
      .select("id,code")
      .single();
    if (error) throw new Error(translateDbError(error.message));
    id = data.id;

    /*
     * Deliberately not fatal. The project is saved and correct; the slug is a
     * value nothing reads. Failing the whole save here would tell the engineer
     * his project was lost when it is sitting right there.
     */
    const { error: slugError } = await supabase
      .from("projects")
      .update({ slug: await resolveSlug(supabase, data.code, id) })
      .eq("id", id);
    if (slugError) console.error("[projects] slug", slugError.message);
  } catch (error) {
    return { error: error instanceof Error ? error.message : "الحفظ فشل" };
  }

  publicRevalidate();
  redirect(`/admin/projects/${id}`);
}

export async function updateProject(
  id: string,
  _previous: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  await requireAdmin();
  const supabase = requireDb();

  try {
    const client_id = await resolveClientId(formData);
    const payload = { ...projectPayload(formData), client_id };

    // Keep the original approval timestamp instead of stamping a new one on
    // every save; only clear it when publication is withdrawn.
    if (payload.publish_approved_at) {
      const { data: existing } = await supabase
        .from("projects")
        .select("publish_approved_at")
        .eq("id", id)
        .maybeSingle();
      if (existing?.publish_approved_at) payload.publish_approved_at = existing.publish_approved_at;
    }

    const { error } = await supabase.from("projects").update(payload).eq("id", id);
    if (error) throw new Error(translateDbError(error.message));
  } catch (error) {
    return { error: error instanceof Error ? error.message : "الحفظ فشل" };
  }

  publicRevalidate();
  revalidatePath(`/admin/projects/${id}`);
  return { error: null, savedAt: Date.now() };
}

/** Postgres constraint messages are unreadable; name the field that clashed. */
function translateDbError(message: string): string {
  if (message.includes("projects_slug_key")) return "الـ slug ده مستخدم في مشروع تاني";
  if (message.includes("projects_code_key")) return "كود المشروع اتكرر — جرب تاني";
  return message;
}

/*
 * An unguarded deleteProject(id) used to live here. Nothing in the interface
 * called it, but a Server Action is a public HTTP endpoint in its own right:
 * any authenticated admin session could have destroyed a project carrying a
 * full ledger, and it left every storage object behind, orphaned and still
 * costing quota.
 *
 * The replacement is at the bottom of this file, under "project lifecycle".
 * It counts the ledger server-side, requires the code to be typed back, and
 * removes the storage objects explicitly.
 */

// ------------------------------------------------------------------ ledger

/**
 * Batch upsert for the spreadsheet grid. Rows arrive dirty-only; new rows come
 * back with the id the database assigned so the client can stop treating them
 * as new.
 */
export async function saveLedger(
  projectId: string,
  kind: LedgerKind,
  rows: LedgerRow[],
): Promise<SavedRow[]> {
  await requireAdmin();
  const supabase = requireDb();

  const saved: SavedRow[] = [];
  const inserts: { key: string; payload: Record<string, unknown> }[] = [];

  for (const [index, row] of rows.entries()) {
    const amount = parseAmount(row.amount);
    const label = row.text.trim();

    // A row with no description and no amount is just an empty line; skip it.
    if (!label && amount === null) continue;
    if (amount === null) throw new Error(`سطر ${index + 1}: المبلغ مش رقم صحيح`);
    if (!label) throw new Error(`سطر ${index + 1}: الوصف مطلوب`);

    const date = row.date || new Date().toISOString().slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error(`سطر ${index + 1}: التاريخ مش صحيح`);

    const payload =
      kind === "expenses"
        ? {
            project_id: projectId,
            date,
            item_ar: label,
            amount,
            stage_id: row.stageId || null,
            sort_order: index,
          }
        : { project_id: projectId, date, label_ar: label, amount, seq: index };

    if (row.id) {
      const { error } = await supabase.from(kind).update(payload).eq("id", row.id);
      if (error) throw new Error(error.message);
      saved.push({ key: row.key, id: row.id });
    } else {
      inserts.push({ key: row.key, payload });
    }
  }

  if (inserts.length > 0) {
    const { data, error } = await supabase
      .from(kind)
      .insert(inserts.map((entry) => entry.payload))
      .select("id");
    if (error) throw new Error(error.message);
    // Supabase preserves input order in the returned rows.
    (data ?? []).forEach((record, index) => {
      saved.push({ key: inserts[index].key, id: record.id });
    });
  }

  publicRevalidate();
  return saved;
}

export async function deleteLedgerRow(kind: LedgerKind, id: string) {
  await requireAdmin();
  const supabase = requireDb();
  const { error } = await supabase.from(kind).delete().eq("id", id);
  if (error) throw new Error(error.message);
  publicRevalidate();
}

// ------------------------------------------------------------------ stages

export async function setStageStatus(
  projectId: string,
  stageId: string,
  status: string,
  note: string,
) {
  await requireAdmin();
  const supabase = requireDb();

  if (!["not_started", "in_progress", "done"].includes(status)) return;

  const today = new Date().toISOString().slice(0, 10);
  const { error } = await supabase.from("project_stages").upsert(
    {
      project_id: projectId,
      stage_id: stageId,
      status,
      note_ar: note.trim() || null,
      started_at: status === "not_started" ? null : today,
      completed_at: status === "done" ? today : null,
    },
    { onConflict: "project_id,stage_id" },
  );

  if (error) throw new Error(error.message);
  publicRevalidate();
  revalidatePath(`/admin/projects/${projectId}`);
}

// ------------------------------------------------------------------ media

const ALLOWED_TYPES = ["image/jpeg", "image/png", "image/webp", "image/avif"];
const MAX_BYTES = 15 * 1024 * 1024;

export async function uploadMedia(projectId: string, formData: FormData) {
  await requireAdmin();
  const supabase = requireDb();

  const files = formData.getAll("files").filter((entry): entry is File => entry instanceof File);
  if (files.length === 0) return;

  for (const file of files) {
    if (file.size === 0) continue;
    if (!ALLOWED_TYPES.includes(file.type)) {
      throw new Error(`نوع الملف مش مدعوم: ${file.name}`);
    }
    if (file.size > MAX_BYTES) {
      throw new Error(`الملف كبير أوي (الحد 15 ميجا): ${file.name}`);
    }

    // Unguessable path; the bucket is private but paths should not be enumerable.
    const extension = file.name.split(".").pop()?.toLowerCase() ?? "jpg";
    const path = `${projectId}/${crypto.randomUUID()}.${extension}`;

    const { error: uploadError } = await supabase.storage
      .from("media")
      .upload(path, file, { contentType: file.type, upsert: false });
    if (uploadError) throw new Error(uploadError.message);

    const { error } = await supabase.from("project_media").insert({
      project_id: projectId,
      url: path,
      type: "image",
      is_public: false, // nothing is published until explicitly approved
    });
    if (error) throw new Error(error.message);
  }

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

export async function updateMedia(
  id: string,
  projectId: string,
  patch: { stage_id?: string | null; is_public?: boolean; caption_ar?: string | null },
) {
  await requireAdmin();
  const supabase = requireDb();

  const clean: Record<string, unknown> = {};
  if ("stage_id" in patch) clean.stage_id = patch.stage_id || null;
  if ("caption_ar" in patch) clean.caption_ar = patch.caption_ar?.trim() || null;
  if ("is_public" in patch) clean.is_public = Boolean(patch.is_public);
  // `phase` was accepted here. The column stays and old values stay with it,
  // but nothing reads it and the admin no longer offers it.

  const { error } = await supabase.from("project_media").update(clean).eq("id", id);
  if (error) throw new Error(error.message);

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

export async function deleteMedia(id: string, projectId: string, path: string) {
  await requireAdmin();
  const supabase = requireDb();

  await supabase.storage.from("media").remove([path]);
  const { error } = await supabase.from("project_media").delete().eq("id", id);
  if (error) throw new Error(error.message);

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

