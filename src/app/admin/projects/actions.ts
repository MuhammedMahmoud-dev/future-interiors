/**
 * Batch upsert for the spreadsheet grid. Rows arrive dirty-only; new rows come
 * back with the id the database assigned so the client can stop treating them
 * as new.
 */
export async function saveLedger(
  projectId: string,
  kind: LedgerKind,
  rows: LedgerRow[],
): Promise<SavedRow[]> {
  await requireAdmin();
  const supabase = requireDb();

  const saved: SavedRow[] = [];
  const inserts: { key: string; payload: Record<string, unknown> }[] = [];

  for (const [index, row] of rows.entries()) {
    const amount = parseAmount(row.amount);
    const label = row.text.trim();

    // A row with no description and no amount is just an empty line; skip it.
    if (!label && amount === null) continue;
    if (amount === null) throw new Error(`سطر ${index + 1}: المبلغ مش رقم صحيح`);
    if (!label) throw new Error(`سطر ${index + 1}: الوصف مطلوب`);

    const date = row.date || new Date().toISOString().slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error(`سطر ${index + 1}: التاريخ مش صحيح`);

    const payload =
      kind === "expenses"
        ? {
            project_id: projectId,
            date,
            item_ar: label,
            amount,
            stage_id: row.stageId || null,
            sort_order: index,
          }
        : { project_id: projectId, date, label_ar: label, amount, seq: index };

    if (row.id) {
      const { error } = await supabase.from(kind).update(payload).eq("id", row.id);
      if (error) throw new Error(error.message);
      saved.push({ key: row.key, id: row.id });
    } else {
      inserts.push({ key: row.key, payload });
    }
  }

  if (inserts.length > 0) {
    const { data, error } = await supabase
      .from(kind)
      .insert(inserts.map((entry) => entry.payload))
      .select("id");
    if (error) throw new Error(error.message);
    // Supabase preserves input order in the returned rows.
    (data ?? []).forEach((record, index) => {
      saved.push({ key: inserts[index].key, id: record.id });
    });
  }

  publicRevalidate();
  return saved;
}

export async function deleteLedgerRow(kind: LedgerKind, id: string) {
  await requireAdmin();
  const supabase = requireDb();
  const { error } = await supabase.from(kind).delete().eq("id", id);
  if (error) throw new Error(error.message);
  publicRevalidate();
}

// ------------------------------------------------------------------ stages

export async function setStageStatus(
  projectId: string,
  stageId: string,
  status: string,
  note: string,
) {
  await requireAdmin();
  const supabase = requireDb();

  if (!["not_started", "in_progress", "done"].includes(status)) return;

  const today = new Date().toISOString().slice(0, 10);
  const { error } = await supabase.from("project_stages").upsert(
    {
      project_id: projectId,
      stage_id: stageId,
      status,
      note_ar: note.trim() || null,
      started_at: status === "not_started" ? null : today,
      completed_at: status === "done" ? today : null,
    },
    { onConflict: "project_id,stage_id" },
  );

  if (error) throw new Error(error.message);
  publicRevalidate();
  revalidatePath(`/admin/projects/${projectId}`);
}

