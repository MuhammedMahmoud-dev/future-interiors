/**
 * Archiving is the ordinary way to retire a project, and the interface leads
 * with it. Same semantics as archiving a client: it hides the project from the
 * admin list and nothing else.
 *
 * It must never touch portal access — that is portal_access_enabled, a separate
 * and explicit decision — and never public visibility, which stays is_public
 * AND publish_approved_at. A finished project is the likeliest thing to be
 * archived, and its photographs are exactly what belongs in the gallery.
 */
export async function setProjectArchived(id: string, archived: boolean) {
  await requireAdmin();
  const supabase = requireDb();

  const { error } = await supabase
    .from("projects")
    .update({ archived_at: archived ? new Date().toISOString() : null })
    .eq("id", id);
  if (error) throw new Error(error.message);

  revalidatePath("/admin/projects");
  revalidatePath(`/admin/projects/${id}`);
}

export type DeleteProjectState = { error: string | null };

/**
 * Permanently deletes a project — only ever one that was entered by mistake.
 *
 * Three things guard it, and the first is the one that matters:
 *
 * 1. THE LEDGER MUST BE EMPTY. Counted here, on the server, every time. The
 *    disabled button in the UI is a courtesy, not a control: a Server Action is
 *    its own public HTTP endpoint and anyone can call it with any id. A project
 *    carrying a single expense row is a financial record, and there is no safe
 *    delete for one — that is what archiving is for.
 * 2. The typed code must match, so the confirmation names which project is
 *    going rather than asking a yes/no question nobody reads.
 * 3. requireAdmin, like every action in this file.
 *
 * Storage is deleted explicitly. project_media ROWS cascade with the project,
 * but the objects they point at live in the bucket and would be orphaned —
 * invisible, unreferenced, and still costing quota.
 *
 * The client is never touched. They may hold other projects, and the FK is
 * ON DELETE RESTRICT precisely so a ledger cannot lose its owner.
 */
export async function deleteProject(
  _previous: DeleteProjectState,
  formData: FormData,
): Promise<DeleteProjectState> {
  await requireAdmin();
  const supabase = requireDb();

  const id = String(formData.get("id") ?? "");
  const typed = String(formData.get("confirm") ?? "").trim().toUpperCase();
  if (!id) return { error: "مشروع غير معروف." };

  const { data: project } = await supabase
    .from("projects")
    .select("id,code,title_ar,client_id,cover_image")
    .eq("id", id)
    .maybeSingle();

  if (!project) return { error: "المشروع مش موجود." };

  // Counted server-side on every call, never trusted from the client.
  const [{ count: expenses }, { count: payments }] = await Promise.all([
    supabase.from("expenses").select("id", { count: "exact", head: true }).eq("project_id", id),
    supabase.from("payments").select("id", { count: "exact", head: true }).eq("project_id", id),
  ]);

  // The rule itself lives in lib/projectLifecycle so a test can call it
  // instead of inspecting this file's text. See projectDelete.test.ts.
  const counts = { expenses: expenses ?? 0, payments: payments ?? 0 };
  if (ledgerBlocksDelete(counts)) return { error: ledgerRefusal(counts) };

  if (typed !== project.code.toUpperCase()) {
    return { error: "كود المشروع اللي كتبته مش مطابق." };
  }

  /*
   * Storage does not cascade; collect the objects before the rows go.
   *
   * The cover joins the media here. It used to be left behind, because the
   * sweep only read project_media — which is how three orphaned objects ended
   * up sitting in the bucket after a delete, paying for storage and belonging
   * to nothing.
   *
   * Every path collected is this project's own. gallery_images is a separate
   * table with no link to projects, so nothing here can reach a gallery
   * photograph — which is the whole point of that split, and is asserted by
   * verify:gallery.
   */
  const { data: media } = await supabase
    .from("project_media")
    .select("url")
    .eq("project_id", id);

  const paths = [
    ...(media ?? []).map((row) => row.url),
    project.cover_image,
  ].filter((path): path is string => Boolean(path));

  if (paths.length > 0) await supabase.storage.from("media").remove(paths);

  const { error: deleteError } = await supabase.from("projects").delete().eq("id", id);
  if (deleteError) return { error: deleteError.message };

  /*
   * Logged after the delete succeeds, not before: a log entry for a project
   * that is still there would be worse than none. Deletion requires an empty
   * ledger, so nothing financial is lost — what this preserves is that the code
   * existed at all, which is the thing people ask about weeks later.
   */
  await supabase.from("deleted_projects_log").insert({
    code: project.code,
    title_ar: project.title_ar,
    client_id: project.client_id,
  });

  revalidatePath("/admin/projects");
  publicRevalidate();
  redirect("/admin/projects");
}
