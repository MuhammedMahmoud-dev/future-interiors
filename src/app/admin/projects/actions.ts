const ALLOWED_TYPES = ["image/jpeg", "image/png", "image/webp", "image/avif"];
const MAX_BYTES = 15 * 1024 * 1024;

export async function uploadMedia(projectId: string, formData: FormData) {
  await requireAdmin();
  const supabase = requireDb();

  const files = formData.getAll("files").filter((entry): entry is File => entry instanceof File);
  if (files.length === 0) return;

  for (const file of files) {
    if (file.size === 0) continue;
    if (!ALLOWED_TYPES.includes(file.type)) {
      throw new Error(`نوع الملف مش مدعوم: ${file.name}`);
    }
    if (file.size > MAX_BYTES) {
      throw new Error(`الملف كبير أوي (الحد 15 ميجا): ${file.name}`);
    }

    // Unguessable path; the bucket is private but paths should not be enumerable.
    const extension = file.name.split(".").pop()?.toLowerCase() ?? "jpg";
    const path = `${projectId}/${crypto.randomUUID()}.${extension}`;

    const { error: uploadError } = await supabase.storage
      .from("media")
      .upload(path, file, { contentType: file.type, upsert: false });
    if (uploadError) throw new Error(uploadError.message);

    const { error } = await supabase.from("project_media").insert({
      project_id: projectId,
      url: path,
      type: "image",
      is_public: false, // nothing is published until explicitly approved
    });
    if (error) throw new Error(error.message);
  }

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

export async function updateMedia(
  id: string,
  projectId: string,
  patch: { stage_id?: string | null; phase?: string | null; is_public?: boolean; caption_ar?: string | null },
) {
  await requireAdmin();
  const supabase = requireDb();

  const clean: Record<string, unknown> = {};
  if ("stage_id" in patch) clean.stage_id = patch.stage_id || null;
  if ("caption_ar" in patch) clean.caption_ar = patch.caption_ar?.trim() || null;
  if ("is_public" in patch) clean.is_public = Boolean(patch.is_public);
  if ("phase" in patch) {
    clean.phase = patch.phase && ["before", "during", "after"].includes(patch.phase) ? patch.phase : null;
  }

  const { error } = await supabase.from("project_media").update(clean).eq("id", id);
  if (error) throw new Error(error.message);

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

export async function deleteMedia(id: string, projectId: string, path: string) {
  await requireAdmin();
  const supabase = requireDb();

  await supabase.storage.from("media").remove([path]);
  const { error } = await supabase.from("project_media").delete().eq("id", id);
  if (error) throw new Error(error.message);

  revalidatePath(`/admin/projects/${projectId}`);
  publicRevalidate();
}

