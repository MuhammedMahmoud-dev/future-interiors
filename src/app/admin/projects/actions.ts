/**
 * Every action here re-checks the admin session. A Server Action is a public
 * HTTP endpoint — being rendered by a guarded page is not itself protection.
 *
 * Writes use the service_role client, which is the only thing RLS lets through.
 */

export type LedgerKind = "expenses" | "payments";

export type LedgerRow = {
  /** Stable client-side key. New rows have no id yet. */
  key: string;
  id: string | null;
  date: string;
  text: string;
  amount: string;
  stageId?: string | null;
};

export type SavedRow = { key: string; id: string };

function publicRevalidate() {
  // Content and projects feed the public site and the client portal alike.
  revalidatePath("/[locale]", "layout");
}

function requireDb() {
  const supabase = getSupabase();
  if (!supabase) throw new Error("Supabase is not configured");
  return supabase;
}

/** Empty string -> null, so optional columns stay NULL instead of "". */
function text(formData: FormData, field: string): string | null {
  const value = String(formData.get(field) ?? "").trim();
  return value === "" ? null : value;
}

/**
 * Turns the form's client selection into a client_id.
 *
 * Either an existing client was picked, or a new one was typed in. On the new
 * path, a phone that already belongs to someone links to that existing client
 * rather than erroring on the unique index — a returning client opening a
 * second apartment is the case this table was added for, and it should not read
 * as a validation failure.
 */
async function resolveClientId(formData: FormData): Promise<string | null> {
  const existing = String(formData.get("client_id") ?? "").trim();
  if (existing) return existing;

  const name = String(formData.get("new_client_name") ?? "").trim();
  const phone = normalizePhone(String(formData.get("new_client_phone") ?? ""));

  // Neither picked nor typed: leave the project unlinked rather than inventing
  // a blank client. The admin can attach one later.
  if (!name && !phone) return null;

  if (!name) throw new Error("اسم العميل مطلوب");
  if (!/^1\d{9}$/.test(phone)) throw new Error("رقم موبايل العميل مش صحيح (مثال: 01115134141)");

  const supabase = requireDb();

  const { data: match } = await supabase
    .from("clients")
    .select("id")
    .eq("phone", phone)
    .maybeSingle();
  if (match) return match.id as string;

  const { data, error } = await supabase
    .from("clients")
    .insert({ name, phone })
    .select("id")
    .single();
  if (error) throw new Error(error.message);

  return data.id as string;
}

function projectPayload(formData: FormData) {
  const rate = parseAmount(String(formData.get("supervision_rate") ?? ""));
  const area = parseAmount(String(formData.get("area_m2") ?? ""));
  const status = String(formData.get("status") ?? "in_progress");

  if (rate === null || rate < 0 || rate > 1) {
    throw new Error("نسبة الإشراف لازم تكون بين 0 و 1 (مثال: 0.15)");
  }
  if (!["in_progress", "completed", "on_hold"].includes(status)) {
    throw new Error("حالة المشروع مش صحيحة");
  }

  const title = String(formData.get("title_ar") ?? "").trim();
  if (!title) throw new Error("عنوان المشروع مطلوب");

  const slug = String(formData.get("slug") ?? "").trim().toLowerCase();
  if (!/^[a-z0-9-]+$/.test(slug)) {
    throw new Error("الـ slug لازم يكون حروف إنجليزي صغيرة وأرقام وشرطات بس");
  }

  return {
    title_ar: title,
    title_en: text(formData, "title_en"),
    slug,
    description_ar: text(formData, "description_ar"),
    description_en: text(formData, "description_en"),
    unit_no: text(formData, "unit_no"),
    building_no: text(formData, "building_no"),
    supervision_rate: rate,
    compound: text(formData, "compound"),
    district: text(formData, "district"),
    area_m2: area,
    start_date: text(formData, "start_date"),
    end_date: text(formData, "end_date"),
    status,
    is_public: formData.get("is_public") === "on",
    // Publishing requires an explicit approval timestamp as well as the flag.
    publish_approved_at:
      formData.get("publish_approved_at") === "on" ? new Date().toISOString() : null,
  };
}

/** Validation failures come back as a message for the form; success redirects. */
export type ProjectFormState = { error: string | null; savedAt?: number };

export async function createProject(
  _previous: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  await requireAdmin();
  const supabase = requireDb();

  let id: string;
  try {
    const client_id = await resolveClientId(formData);
    // code is generated by the database default, never by the app.
    const { data, error } = await supabase
      .from("projects")
      .insert({ ...projectPayload(formData), client_id })
      .select("id")
      .single();
    if (error) throw new Error(translateDbError(error.message));
    id = data.id;
  } catch (error) {
    return { error: error instanceof Error ? error.message : "الحفظ فشل" };
  }

  publicRevalidate();
  redirect(`/admin/projects/${id}`);
}

export async function updateProject(
  id: string,
  _previous: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  await requireAdmin();
  const supabase = requireDb();

  try {
    const client_id = await resolveClientId(formData);
    const payload = { ...projectPayload(formData), client_id };

    // Keep the original approval timestamp instead of stamping a new one on
    // every save; only clear it when publication is withdrawn.
    if (payload.publish_approved_at) {
      const { data: existing } = await supabase
        .from("projects")
        .select("publish_approved_at")
        .eq("id", id)
        .maybeSingle();
      if (existing?.publish_approved_at) payload.publish_approved_at = existing.publish_approved_at;
    }

    const { error } = await supabase.from("projects").update(payload).eq("id", id);
    if (error) throw new Error(translateDbError(error.message));
  } catch (error) {
    return { error: error instanceof Error ? error.message : "الحفظ فشل" };
  }

  publicRevalidate();
  revalidatePath(`/admin/projects/${id}`);
  return { error: null, savedAt: Date.now() };
}

/** Postgres constraint messages are unreadable; name the field that clashed. */
function translateDbError(message: string): string {
  if (message.includes("projects_slug_key")) return "الـ slug ده مستخدم في مشروع تاني";
  if (message.includes("projects_code_key")) return "كود المشروع اتكرر — جرب تاني";
  return message;
}

export async function setProjectStatus(id: string, status: string) {
  await requireAdmin();
  const supabase = requireDb();
  if (!["in_progress", "completed", "on_hold"].includes(status)) return;
  await supabase.from("projects").update({ status }).eq("id", id);
  publicRevalidate();
  revalidatePath("/admin/projects");
}

export async function deleteProject(id: string) {
  await requireAdmin();
  const supabase = requireDb();
  // Expenses, payments, stages and media cascade via the schema.
  const { error } = await supabase.from("projects").delete().eq("id", id);
  if (error) throw new Error(error.message);
  publicRevalidate();
  redirect("/admin/projects");
}

